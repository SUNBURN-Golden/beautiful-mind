import { createClient } from '@supabase/supabase-js';
import * as dotenv from 'dotenv';
import path from 'path';

const envPath = path.resolve(process.cwd(), '.env.local');
const envConfig = dotenv.config({ path: envPath }).parsed;
for (const k in envConfig) {
  process.env[k] = envConfig[k];
}

const supabaseUrl = process.env.NEXT_PUBLIC_SUPABASE_URL;
const serviceKey = process.env.SUPABASE_SERVICE_ROLE_KEY;
const s = createClient(supabaseUrl, serviceKey);

async function verifyL1Gates() {
  console.log('=== STARTING L1-READINESS SAFE-GATE VERIFICATION ===\n');

  // (1) Gate B: Idempotency ledger evidence (via REST API)
  console.log('[GATE B] Idempotency ledger evidence (recent keys)\n');
  const { data: ledgerRecords, error: ledgerErr } = await s
    .from('token_ledger')
    .select('idempotency_key, type')
    .in('type', ['SLASHING_BURN', 'GAS_FEE_BURN'])
    .not('idempotency_key', 'is', null);

  if (ledgerErr) {
    console.error('Failed to fetch ledger:', ledgerErr);
  } else {
    const counts = {};
    for (const row of ledgerRecords) {
      // Only capture sweep/unlock idempotency keys generated by E2E proofs
      if (row.idempotency_key.startsWith('SLASH_NO_REVIEW') || row.idempotency_key.startsWith('UNLOCK_FEE')) {
        counts[row.idempotency_key] = (counts[row.idempotency_key] || 0) + 1;
      }
    }

    const output = Object.keys(counts).map(key => ({
      idempotency_key: key,
      count: counts[key],
      expected_type: key.startsWith('SLASH') ? 'SLASHING_BURN' : 'GAS_FEE_BURN'
    }));

    console.table(output);
  }

  // (2) Gates requiring raw Postgres connections
  console.log('\n========================================================');
  console.log('NOTICE: RLS and Triggers require direct Postgres queries.');
  console.log('Because `DATABASE_URL` is omitted locally, please run the');
  console.log('following 3 exact SQL queries in your Supabase SQL Editor:');
  console.log('========================================================\n');

  console.log(`-- (1) Trigger evidence (DELETE-safe)
SELECT event_object_table AS table_name, trigger_name, action_timing, event_manipulation
FROM information_schema.triggers
WHERE event_object_schema='public'
  AND event_object_table IN (
    'token_ledger','token_holds','audit_logs',
    'review_sessions','review_facts','review_questions','review_drafts','review_signatures',
    'review_session_raw','review_unlocks'
  )
ORDER BY table_name, trigger_name;
`);

  console.log(`-- (2) Policies evidence (RLS party-read / target unlock)
SELECT schemaname, tablename, policyname, cmd, qual
FROM pg_policies
WHERE schemaname='public'
  AND tablename IN ('review_signatures','review_session_raw','review_unlocks','token_ledger','token_holds')
ORDER BY tablename, policyname;
`);

  console.log(`-- (3) Ledger immutability quick check
SELECT trg.tgname as trigger_name, tbl.relname as table_name
FROM pg_trigger trg
JOIN pg_class tbl ON trg.tgrelid = tbl.oid
WHERE tbl.relname = 'token_ledger'
  AND trg.tgname = 'block_ledger_mutation';

SELECT policyname, cmd FROM pg_policies
WHERE tablename = 'token_ledger';
`);

  console.log('\n=== SQL GATES VERIFICATION SCRIPT EXECUTED ===');
}

verifyL1Gates().catch(console.error);
